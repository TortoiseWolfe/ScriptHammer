#!/usr/bin/env node
/**
 * Emit the `<link rel="preload">` list for the vendored fonts (#740).
 *
 * WHAT WAS LOST. `next/font` used to emit eight `<link rel="preload" as="font" crossorigin>`
 * tags. Vendoring the faces (#730) removed the dependency on fonts.gstatic.com and took the
 * preloads with it, so the browser has to parse the CSS and reach layout before it starts
 * fetching a face. The faces still load, `font-display: swap` still applies, and the six
 * `size-adjust` fallbacks still prevent layout shift — what is lost is discovery time on a
 * cold cache.
 *
 * IT EMITS IMPORTS, NOT URLS, AND THAT IS THE POINT. The bundler fingerprints these files a
 * SECOND time — `x-s.p.woff2` ships as `x-s.p.1a4aa509.woff2` — so any literal URL written
 * here is wrong the moment a font changes. An import hands that job to the bundler, which is
 * the only thing that always knows the answer. This script decides only WHICH files preload.
 *
 * `next/font` already made that call: the `.p` in a filename is its own "preload this" flag,
 * inherited rather than re-derived.
 *
 * IT READS THE COMMITTED CSS, NOT A BUILD, DELIBERATELY. Its sibling
 * `vendor-google-fonts.mjs` reads `out/` and must only be run after one specific build; run
 * it after the wrong one and it rewrites `fonts.generated.css` from an incomplete stylesheet.
 * That happened while writing this (735 lines down to 71, reverted). Deriving from the
 * committed file instead makes this safe to run at any time, and idempotent.
 *
 * Usage: node scripts/fonts/generate-preload-list.mjs [--check]
 *   --check  exit 1 if the generated file is out of date, and write nothing
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const CSS = join(ROOT, 'src', 'app', 'fonts.generated.css');
const OUT = join(ROOT, 'src', 'app', 'fonts-preload.generated.ts');
const CHECK = process.argv.includes('--check');

const css = readFileSync(CSS, 'utf8');

// Every `.p` face the committed stylesheet actually references. Reading the CSS rather than
// listing the directory matters: src/fonts/ can hold orphans (the vendoring script warns
// about them rather than deleting), and preloading a face no @font-face uses would download
// bytes the page never renders.
const files = [
  ...new Set(
    Array.from(css.matchAll(/\.\.\/fonts\/([\w-]+-s\.p\.woff2)/g), (m) => m[1])
  ),
].sort();

if (!files.length) {
  console.error(
    `::error::no preloadable (-s.p.woff2) faces referenced by ${CSS.replace(ROOT + '/', '')}. ` +
      `Either the naming convention changed or the stylesheet is truncated — refusing to ` +
      `write an empty preload list.`
  );
  process.exit(1);
}

const module = `/*
 * GENERATED by scripts/fonts/generate-preload-list.mjs — do not hand-edit (#740).
 *
 * The faces next/font marked preloadable (the \`.p\` in each filename), imported so the
 * bundler resolves the content hash it adds at build time. A literal path here would be
 * stale the moment a font changed.
 *
 * Regenerate after re-vendoring:  node scripts/fonts/generate-preload-list.mjs
 */
${files.map((f, i) => `import face${i} from '../fonts/${f}';`).join('\n')}

/** Rendered as <link rel="preload" as="font" crossorigin> by src/app/layout.tsx. */
export const PRELOAD_FONTS: readonly string[] = [
${files.map((_, i) => `  face${i},`).join('\n')}
];
`;

if (CHECK) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as out of date */
  }
  if (current !== module) {
    console.error(
      `::error::${OUT.replace(ROOT + '/', '')} is out of date. Run ` +
        `\`node scripts/fonts/generate-preload-list.mjs\` and commit the result.`
    );
    process.exit(1);
  }
  console.log(`  preload list is current — ${files.length} face(s)`);
  process.exit(0);
}

writeFileSync(OUT, module);
console.log(`  wrote ${OUT.replace(ROOT + '/', '')} — ${files.length} face(s)`);
for (const f of files) console.log(`    ${f}`);
