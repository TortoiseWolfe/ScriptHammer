#!/usr/bin/env node
/**
 * Vendor the Google fonts `next/font` downloads, so the BUILD stops needing Google (#730).
 *
 * THE PROBLEM. `next/font/google` fetches every face from `fonts.gstatic.com` at BUILD
 * time. The comment it replaced said "self-hosts these at build time, so there is no
 * request to fonts.googleapis.com at runtime" — true, and the wrong half of the problem.
 * A blip at Google fails the build of an unrelated change. Measured twice in twelve hours:
 * it killed the production deploy of a walk-mode hotfix (which then sat undeployed until
 * someone re-ran it), and it killed `chromium-gen 6/6` in the local E2E lane, which built
 * nothing and so executed 0 tests.
 *
 * WHY NOT `next/font/local`. It cannot express this. Its `declarations` option applies per
 * CALL, but the shipped CSS carries 28 distinct `unicode-range` values that must differ per
 * SLICE — 34 files across 6 families. One call cannot emit per-slice ranges, and one call
 * per slice would emit a separate font-family per slice.
 *
 * WHY NOT A BUILD CACHE. There isn't one. Next re-fetches on every build; nothing lands on
 * disk outside `.next/static`, so there is nothing for CI to cache.
 *
 * SO: take the CSS Next already generates and point it at committed files. Copying its
 * output verbatim is the entire safety argument — the `unicode-range` splits, the
 * `size-adjust` fallback metrics that prevent layout shift, the `font-display`, and the
 * exact family names all survive because they are not being re-derived. Typography cannot
 * drift, because the declarations are the same bytes.
 *
 * WHY THE FILES LIVE IN `src/fonts/` AND NOT `public/`. A `url()` in CSS under `src/` is
 * resolved and fingerprinted by the bundler into `_next/static/media`, which makes it
 * basePath-correct automatically. A literal `/fonts/x.woff2` under `public/` would be right
 * for the root build and 404 under the `/ScriptHammer` basePath — the #392 trap.
 *
 * USAGE — needs a completed build to read from, and network only insofar as that build did:
 *   docker compose run --rm -e NEXT_PUBLIC_BASE_PATH= -e DISABLE_BASE_PATH=true builder pnpm build
 *   node scripts/fonts/vendor-google-fonts.mjs
 *
 * Re-run it when a family, weight or subset changes. It is idempotent.
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  copyFileSync,
  readdirSync,
} from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..', '..');
const CSS_DIR = join(ROOT, 'out', '_next', 'static', 'css');
const MEDIA_DIR = join(ROOT, 'out', '_next', 'static', 'media');
const FONT_DIR = join(ROOT, 'src', 'fonts');
const OUT_CSS = join(ROOT, 'src', 'app', 'fonts.generated.css');

function fail(msg) {
  console.error(`\n  ERROR: ${msg}\n`);
  process.exit(1);
}

let cssFiles;
try {
  cssFiles = readdirSync(CSS_DIR).filter((f) => f.endsWith('.css'));
} catch {
  fail(
    `no built CSS at ${CSS_DIR}. This script reads a COMPLETED build — run ` +
      `\`docker compose run --rm builder pnpm build\` first.`
  );
}
if (!cssFiles.length) fail(`${CSS_DIR} has no .css files`);

const css = cssFiles
  .map((f) => readFileSync(join(CSS_DIR, f), 'utf8'))
  .join('\n');

// Every @font-face, deduplicated by its full text — Next emits the same face into several
// per-route stylesheets, and vendoring it once is the point.
const blocks = [...new Set(css.match(/@font-face\{[^}]*\}/g) ?? [])];
if (!blocks.length)
  fail('no @font-face blocks found — has next/font already been removed?');

mkdirSync(FONT_DIR, { recursive: true });

const copied = new Set();
let withFile = 0;
let localOnly = 0;

const rewritten = blocks.map((blk) => {
  // `src:url(<basePath>/_next/static/media/<hash>-s[.p].woff2) format("woff2")`
  const m = blk.match(/url\(([^)]*?)([\w-]+-s(?:\.p)?\.woff2)\)/);
  if (!m) {
    // A fallback face: `src:local("Arial")` plus size-adjust/ascent-override. No file to
    // copy, and it is exactly what stops the layout shifting while the real face loads —
    // so it must survive verbatim.
    localOnly++;
    return blk;
  }
  const file = m[2];
  if (!copied.has(file)) {
    try {
      copyFileSync(join(MEDIA_DIR, file), join(FONT_DIR, file));
    } catch {
      fail(
        `@font-face references ${file}, absent from ${MEDIA_DIR} — is the build partial?`
      );
    }
    copied.add(file);
  }
  withFile++;
  // Relative, so the bundler fingerprints it and basePath stays correct.
  return blk.replace(/url\([^)]*\)/, `url('../fonts/${file}')`);
});

const banner = `/*
 * GENERATED by scripts/fonts/vendor-google-fonts.mjs — do not hand-edit (#730).
 *
 * These are the @font-face declarations next/font/google produced, copied verbatim and
 * repointed at committed files in src/fonts/. Copying rather than re-deriving is the safety
 * argument: the unicode-range splits, the size-adjust fallback metrics that prevent layout
 * shift, and the exact family names are preserved because nothing recalculated them.
 *
 * The build no longer contacts fonts.gstatic.com. Regenerate after changing any family,
 * weight or subset, and commit both this file and src/fonts/.
 *
 * ${withFile} faces with a file, ${localOnly} local()/size-adjust fallback faces, ${copied.size} unique woff2.
 */
`;

writeFileSync(OUT_CSS, banner + rewritten.join('\n') + '\n');

// Warn about orphans rather than deleting: a stale file is cheap, and silently removing one
// that something still references is not.
const orphans = readdirSync(FONT_DIR).filter(
  (f) => f.endsWith('.woff2') && !copied.has(f)
);

console.log(
  `  faces:      ${blocks.length}  (${withFile} with a file, ${localOnly} local()/fallback)`
);
console.log(`  woff2:      ${copied.size} copied to src/fonts/`);
console.log(`  stylesheet: ${OUT_CSS.replace(ROOT + '/', '')}`);
if (orphans.length) {
  console.log(
    `\n  ${orphans.length} file(s) in src/fonts/ are no longer referenced:`
  );
  for (const o of orphans) console.log(`    ${o}`);
  console.log(
    '  Delete them by hand once you have confirmed nothing else wants them.'
  );
}
