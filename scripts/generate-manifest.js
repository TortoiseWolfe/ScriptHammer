#!/usr/bin/env node

/**
 * Generate PWA manifest.json at build time
 * This replaces the dynamic API route for static export compatibility
 */

const fs = require('fs');
const path = require('path');
const {
  deployedBasePath,
  normaliseBasePath,
} = require('./lib/deployed-base-path');

// Load project configuration
const projectConfigPath = path.join(
  __dirname,
  '../src/config/project-detected.json'
);
let projectConfig = {
  projectName: 'ScriptHammer',
  projectOwner: 'TortoiseWolfe',
  basePath: '',
};

// Try to load the auto-detected configuration
if (fs.existsSync(projectConfigPath)) {
  try {
    const detected = JSON.parse(fs.readFileSync(projectConfigPath, 'utf8'));
    projectConfig = {
      ...projectConfig,
      ...detected,
    };
  } catch (error) {
    console.warn(
      'Warning: Could not load project-detected.json:',
      error.message
    );
  }
}

// Use environment variables if available (highest priority)
if (process.env.NEXT_PUBLIC_PROJECT_NAME) {
  projectConfig.projectName = process.env.NEXT_PUBLIC_PROJECT_NAME;
}
if (process.env.NEXT_PUBLIC_PROJECT_OWNER) {
  projectConfig.projectOwner = process.env.NEXT_PUBLIC_PROJECT_OWNER;
}
if (process.env.NEXT_PUBLIC_BASE_PATH !== undefined) {
  projectConfig.basePath = process.env.NEXT_PUBLIC_BASE_PATH;
}

/**
 * The description a forker actually supplied (#982).
 *
 * This used to be a hardcoded sentence with only the project NAME interpolated, so
 * every fork's PWA install prompt described this template:
 * "<Fork> - A production Next.js and Supabase platform with auth, payments, encrypted
 * messaging, and an accessible offline-capable PWA". The manifest is regenerated by
 * prebuild, so that string SHIPPED — it is the text in the Android install sheet and
 * the desktop install dialog.
 *
 * #923 taught rebrand.sh to write `projectDescription` into project.config.ts, and
 * fixed og:description, twitter:description and the meta description to read it. Its
 * PR body claimed the manifest was covered too. It was not: nothing here consulted
 * that field, and the substitution sweep cannot reach the sentence either, because it
 * contains no brand token — which is the whole reason #923 existed.
 *
 * Read with a regex rather than an import because this script is plain node with only
 * fs and path, and runs before anything is installed. Same approach
 * generated-manifest.test.js already uses to read projectName out of the same file.
 */
function projectDescription() {
  const configPath = path.join(__dirname, '../src/config/project.config.ts');
  try {
    const src = fs.readFileSync(configPath, 'utf8');
    // Prettier wraps this value onto its own line, so the pattern spans the break.
    const match = /projectDescription:\s*'((?:[^'\\]|\\.)*)'/.exec(src);
    if (match) return match[1].replace(/\\'/g, "'");
  } catch {
    // Fall through to the generic sentence below.
  }
  return `${projectConfig.projectName} - A production Next.js and Supabase platform with auth, payments, encrypted messaging, and an accessible offline-capable PWA`;
}

